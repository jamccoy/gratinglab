"""
The blaze-angle pipeline in analyzer.py.

Until now this path was verified only by diffing CSV output against stored
baselines (docs/BASELINES.md). A diff proves the numbers moved; it cannot say
which step moved them. These tests pin the arithmetic instead: the variance
decomposition, the ICC correction, the period bookkeeping, and the shape of the
result dict, each checked against values computed by hand.

The end-to-end tests use a synthetic sawtooth of known blaze angle rather than a
real scan. A real scan has no ground truth to compare against - it can only be
compared to its own previous output, which is what the baselines already do.

Run directly:
    .venv/bin/python tests/test_analyzer.py
"""
