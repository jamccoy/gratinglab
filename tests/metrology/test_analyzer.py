# ── End to end, against a known angle ────────────────────────────────────────

# The pipeline recovers the synthetic angle about 0.15 deg low, and does so
# whatever the sampling density - it is the linear detrend of a finite window
# biasing the facet slope, not a discretisation error. The tolerance below
# leaves room for that without admitting a real regression, which would show up
# as degrees rather than tenths.
ANGLE_TOL_DEG = 0.5


def test_the_traditional_path_recovers_the_known_blaze_angle():
    result = _quiet(_analyze_single_file_traditional, _grating_path(),
                    show_plots=False, settings=_settings(use_row_groups=False))

    assert result is not None
    assert result['n_grooves'] > 0
    assert abs(result['mean_angle'] - BLAZE_ANGLE_DEG) < ANGLE_TOL_DEG, \
        f"recovered {result['mean_angle']:.3f} deg from a {BLAZE_ANGLE_DEG} deg facet"
    assert np.isclose(result['period_nm'], PERIOD_NM, atol=1.0), result['period_nm']


def test_the_row_group_path_recovers_the_known_blaze_angle():
    result = _quiet(analyze_single_file_with_row_groups, _grating_path(),
                    show_plots=False, settings=_settings(use_row_groups=True))

    assert result is not None
    assert abs(result['mean_angle'] - BLAZE_ANGLE_DEG) < ANGLE_TOL_DEG, \
        f"recovered {result['mean_angle']:.3f} deg from a {BLAZE_ANGLE_DEG} deg facet"
    assert result['n_groups'] == N_ROW_GROUPS
    assert len(result['groove_row_groups']) == len(result['all_angles'])


def test_both_modes_agree_on_the_angle_of_the_same_grating():
    """
    Row grouping measures each groove once per band instead of once per image.
    It should multiply the measurement count without moving the answer.
    """
    traditional = _quiet(_analyze_single_file_traditional, _grating_path(),
                         show_plots=False,
                         settings=_settings(use_row_groups=False))
    row_groups = _quiet(analyze_single_file_with_row_groups, _grating_path(),
                        show_plots=False, settings=_settings(use_row_groups=True))

    assert np.isclose(traditional['mean_angle'], row_groups['mean_angle'],
                      atol=ANGLE_TOL_DEG)
    assert row_groups['n_grooves'] > traditional['n_grooves']


